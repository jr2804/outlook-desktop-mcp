@runtime_checkable
class Namespace(Protocol):
    """The MAPI namespace (outlook.Session)."""

    @property
    def Stores(self) -> Stores:  # ty: ignore[invalid-type-form]  -- see note below
        ...
    @property
    def DefaultStore(self) -> Store: ...
    @property
    def Accounts(self) -> Accounts:  # ty: ignore[invalid-type-form]  -- same self-ref limitation as Stores/Recipients/Folders
        ...
    @property
    def Categories(self) -> Any: ...
    def GetItemFromID(self, entry_id: str, store_id: str | None = ...) -> GenericItem: ...


# NOTE: ty flags `def Stores(self) -> "Stores"`, `def Recipients(self) -> "Recipients"`,
# and `def Folders(self) -> "Folders"` (in `Folder.Folders`) as
# `invalid-type-form` (Variable of type `property` is not allowed in a return type).
# This is a known ty limitation with Protocol self-references: when a property name
# matches a class name in the class body, ty's name resolver picks up the property
# descriptor instead of the class. The Python runtime handles forward-reference
# strings correctly (see test_blank_subject_guard.py which imports _types successfully
# and satisfies all Protocols with mock objects). We accept these ty warnings
# here because the alternative (renaming the Protocols, or using `Self` which
# loses the collection-typed methods like .Add()/.ResolveAll() on Recipients and
# .Item()/.Count() on Stores/Folders) would degrade type safety elsewhere.


@runtime_checkable
class Outlook(Protocol):
    """The top-level Outlook application (COM Application object)."""

    @property
    def Session(self) -> Namespace: ...
    def CreateItem(self, item_type: int) -> Any: ...
    # Low-level COM invocation (used for setting the sending account on meetings)
    @property
    def _oleobj_(self) -> Any: ...
