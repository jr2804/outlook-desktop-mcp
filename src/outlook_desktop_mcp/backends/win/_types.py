@runtime_checkable
class GenericItem(Protocol):
    """A MAPI item — base for mail/appointment/task. Used for ID-based lookup.

    Includes the union of attributes that exist on *any* Outlook item class
    (mail, appointment, task). For type-narrowed access (e.g. ``item.Start``
    for an appointment), declare the local as a specific Protocol
    (``Appointment``, ``MailItem``, ``TaskItem``).
    """

    @property
    def Class(self) -> int: ...
    @property
    def EntryID(self) -> str: ...
    @property
    def Name(self) -> str: ...
    @property
    def Subject(self) -> str: ...
    @property
    def Body(self) -> str: ...
    @Body.setter
    def Body(self, value: str) -> None: ...
    @property
    def HTMLBody(self) -> str: ...
    @HTMLBody.setter
    def HTMLBody(self, value: str) -> None: ...
    @property
    def Categories(self) -> str: ...
    @Categories.setter
    def Categories(self, value: str) -> None: ...
    @property
    def UnRead(self) -> bool: ...
    @UnRead.setter
    def UnRead(self, value: bool) -> None: ...
    @property
    def Attachments(self) -> Any: ...
    @property
    def MeetingStatus(self) -> int: ...
    @MeetingStatus.setter
    def MeetingStatus(self, value: int) -> None: ...
    def Delete(self) -> None: ...
    def Move(self, folder: Folder) -> Self: ...
    def Save(self) -> None: ...
    def Send(self) -> None: ...
    def Reply(self, *args: Any) -> Any: ...
    def ReplyAll(self) -> Any: ...
    def Respond(self, response: Any, *args: Any) -> Any: ...


