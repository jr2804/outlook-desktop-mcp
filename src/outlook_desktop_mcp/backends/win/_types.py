"""
COM object type stubs for the outlook-desktop-mcp package.

pywin32 exposes Outlook's COM API through runtime dispatch, which means
the actual Python types are dynamic (no static type info). To get useful
type-checking and IDE help without depending on the unmaintained
`win32com.client` stubs, we declare a small set of Protocol classes that
describe only the methods/properties we actually call.

These are *structural* types: any COM object with the right attributes will
satisfy them, even though it isn't actually a subclass.

Convention:
    - `Outlook`      — the top-level COM Application object (CreateItem, Session)
    - `Namespace`    — MAPI namespace (Stores, GetItemFromID, DefaultStore)
    - `Store`        — message store (GetDefaultFolder, GetRootFolder, DisplayName)
    - `Folder`       — calendar/mail/task folder (Folders, Items, Name)
    - `Account`      — Outlook account (DeliveryStore)
    - `MailItem`     — Outlook mail item (To, CC, BCC, Subject, Body, Send, ...)
    - `Appointment`  — calendar item (Start, End, Subject, Move, Save, Recipients, ...)
    - `TaskItem`     — task item (Subject, Body, DueDate, Importance, ...)
    - `GenericItem`  — any MAPI item (Class, EntryID, Subject, Body, Delete, ...)
    - `Recipient`    — mail/appointment recipient (Type)

For one-off vars (e.g. `acc` for an account, `appt_obj` for a re-fetched appt)
we use the generic pseudo-type alias `AnyCOM` (= Any) so a quick local rename
isn't blocked by strict type checking.
"""

from __future__ import annotations

from typing import Any, Protocol, Self, runtime_checkable

# Convenience alias for COM objects we don't have a Protocol for.
# Used sparingly — prefer declaring a Protocol when an attribute set is reused.
type AnyCOM = Any


@runtime_checkable
class Folder(Protocol):
    """A calendar/mail/task folder. Used as return type of folder resolution."""

    @property
    def Name(self) -> str: ...
    @property
    def Folders(self) -> Folders:  # ty: ignore[invalid-type-form]  -- see block comment on Stores
        ...
    @property
    def Items(self) -> Any: ...
    @property
    def UnReadItemCount(self) -> int: ...
    def Item(self, index: Any) -> GenericItem: ...


@runtime_checkable
class Folders(Protocol):
    """A collection of Folder objects (Parent.Folders)."""

    @property
    def Count(self) -> int: ...
    def Item(self, index: Any) -> Folder: ...


